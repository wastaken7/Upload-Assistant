def normalize_orpheus_tag(value: str) -> str:
    """Convert free text to Orpheus tag syntax (lowercase, dot separated)."""
    text = unicodedata.normalize("NFKD", str(value or "")).encode("ascii", "ignore").decode("ascii").casefold()
    text = text.replace("&", " and ").replace("'", "")
    text = re.sub(r"[^a-z0-9]+", ".", text).strip(".")
    return ORPHEUS_TAG_ALIASES.get(text, text)


def orpheus_tags(values: Iterable[str], *, keep_unofficial: bool = True) -> tuple[list[str], list[str], list[str]]:
    """Return ``(tags, unofficial, dropped)`` for Orpheus.

    Official tags come first.  Unofficial but valid tags are kept unless
    ``keep_unofficial`` is false; forbidden and invalid tags are dropped.
    """
    official: list[str] = []
    unofficial: list[str] = []
    dropped: list[str] = []
    for value in values:
        # Tag fields often hold several genres in one string.
        for part in re.split(r"\s*[,;/]\s*", str(value or "")):
            if not part.strip():
                continue
            tag = normalize_orpheus_tag(part)
            if not tag or len(tag) < 2 or tag in ORPHEUS_FORBIDDEN_TAGS or tag.isdigit():
                dropped.append(part.strip())
            elif tag in ORPHEUS_OFFICIAL_TAGS:
                if tag not in official:
                    official.append(tag)
            elif tag not in unofficial:
                unofficial.append(tag)
    tags = official + (unofficial if keep_unofficial else [])
    return tags, unofficial, dropped
